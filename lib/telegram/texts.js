// Unitati de masura in rusa (in romana se folosesc etichetele din CRM)
export const UNITS_RU = { bucata: "шт.", litri: "л", kg: "кг", metru: "м", set: "компл.", pachet: "уп.", pereche: "пар" };

const DICT = { ro: RO, ru: RU };

export function T(lang, key, vars = {}) {
  const s = (DICT[lang] || RO)[key] ?? RO[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

// Toate variantele unui buton din meniu (pentru a recunoaste textul in ambele limbi)
export const MENU_KEYS = ["menu_catalog", "menu_cart", "menu_orders", "menu_contacts", "menu_lang"];
export function menuAction(text) {
  for (const key of MENU_KEYS) if (text === RO[key] || text === RU[key]) return key;
  return null;
}
